#!/usr/bin/env python3
"""Generate catalog.go from aria2-next docs/options.md."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(r"C:\source\20261110\aria2-next\docs\options.md")
OUT_JSON = Path(__file__).with_name("catalog.json")
OUT_GO = Path(__file__).with_name("catalog.go")

SECTION_ZH = {
    "Basic": "基本",
    "HTTP, HTTPS and SFTP": "HTTP / HTTPS / SFTP",
    "Files": "文件",
    "BitTorrent": "BitTorrent",
    "Metalink": "Metalink",
    "ED2K": "ED2K",
    "HLS and DASH": "HLS / DASH",
    "RPC": "RPC",
    "Advanced": "高级",
}

# CLI-only / process-lifecycle options that cannot be usefully edited via RPC globals.
SKIP = {
    "version",
    "help",
    "daemon",
    "conf-path",
    "no-conf",
    "show-files",
    "torrent-file",
    "metalink-file",
    "input-file",
    "gid",  # per-task at add time
}


def parse() -> list[dict]:
    text = SRC.read_text(encoding="utf-8")
    sections: list[dict] = []
    cur = None
    for line in text.splitlines():
        if line.startswith("## "):
            cur = line[3:].strip()
            sections.append({"section": cur, "sectionZh": SECTION_ZH.get(cur, cur), "options": []})
            continue
        if not cur or not line.startswith("|"):
            continue
        if "Option" in line and "Value" in line:
            continue
        if line.startswith("| ---"):
            continue
        parts = [p.strip() for p in line.strip("|").split("|")]
        if len(parts) < 4:
            continue
        opt, val, default, desc = parts[:4]
        names = re.findall(r"--([a-z0-9-]+)", opt)
        if not names:
            continue
        name = names[-1]
        if name in SKIP:
            continue
        kind = "text"
        choices: list[str] = []
        if val.strip() == "flag":
            kind = "flag"
        else:
            ch = re.findall(r"`([^`]+)`", val)
            if "|" in val and ch:
                kind = "enum"
                choices = ch
        default = default.strip().strip("`")
        sections[-1]["options"].append(
            {
                "key": name,
                "kind": kind,
                "choices": choices,
                "default": default,
                "desc": desc,
            }
        )
    return [s for s in sections if s["options"]]


def write_go(sections: list[dict]) -> None:
    lines = [
        "// Code generated by gen_catalog.py; DO NOT EDIT.",
        "package options",
        "",
        "// Kind of option value.",
        "const (",
        '\tKindText = "text"',
        '\tKindFlag = "flag"',
        '\tKindEnum = "enum"',
        ")",
        "",
        "// Option is one aria2-next option from the official catalog.",
        "type Option struct {",
        "\tKey     string",
        "\tKind    string",
        "\tChoices []string",
        "\tDefault string",
        "\tDesc    string",
        "}",
        "",
        "// Section groups options.",
        "type Section struct {",
        "\tID    string",
        "\tTitle string",
        "\tItems []Option",
        "}",
        "",
        "// Catalog is the full aria2-next option list (RPC-editable globals + common options).",
        "var Catalog = []Section{",
    ]
    for sec in sections:
        lines.append("\t{")
        lines.append(f'\t\tID:    {json.dumps(sec["section"], ensure_ascii=False)},')
        lines.append(f'\t\tTitle: {json.dumps(sec["sectionZh"], ensure_ascii=False)},')
        lines.append("\t\tItems: []Option{")
        for o in sec["options"]:
            choices = ", ".join(json.dumps(c, ensure_ascii=False) for c in o["choices"])
            lines.append("\t\t\t{")
            lines.append(f'\t\t\t\tKey:     {json.dumps(o["key"], ensure_ascii=False)},')
            lines.append(f'\t\t\t\tKind:    {json.dumps(o["kind"], ensure_ascii=False)},')
            if o["choices"]:
                lines.append(f"\t\t\t\tChoices: []string{{{choices}}},")
            lines.append(f'\t\t\t\tDefault: {json.dumps(o["default"], ensure_ascii=False)},')
            lines.append(f'\t\t\t\tDesc:    {json.dumps(o["desc"], ensure_ascii=False)},')
            lines.append("\t\t\t},")
        lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    OUT_GO.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    sections = parse()
    OUT_JSON.write_text(json.dumps(sections, ensure_ascii=False, indent=2), encoding="utf-8")
    write_go(sections)
    total = sum(len(s["options"]) for s in sections)
    print(f"sections={len(sections)} options={total}")
    print(f"wrote {OUT_GO}")


if __name__ == "__main__":
    main()
